"""Turns the old Expense Tracker spreadsheet into one SQL file to paste into the Supabase SQL editor.

Usage: python3 scripts/xlsx-to-sql.py "/path/to/Expense Tracker.xlsx" you@gmail.com
Writes import/import.sql (ignored by git, it holds your money data).

Everything imported is marked Debit card, because the sheet has no card column. Safe to run twice: every expense has a stable import_key, so repeats are skipped. Income and costs are added only if you have none yet.
"""
import hashlib
import sys
from collections import Counter
from datetime import datetime

import openpyxl

path, email = sys.argv[1], sys.argv[2]
wb = openpyxl.load_workbook(path, data_only=True)
q = lambda s: "'" + str(s).replace("'", "''") + "'"

# Log tab: header in row 4, data from row 5. Dates are Malaysia time (UTC+8).
expenses, seen = [], Counter()
for row in wb['Log'].iter_rows(min_row=5, values_only=True):
    when, desc, cat, amount = row[1], row[2], row[3], row[4]
    if not isinstance(when, datetime) or not isinstance(amount, (int, float)) or amount <= 0:
        continue
    desc = (str(desc or '').strip() or 'Expense')[:200]
    cat = str(cat or 'Others').strip()
    stamp = when.strftime('%Y-%m-%d %H:%M:%S')
    key = hashlib.sha1(f'{stamp}|{desc}|{amount:.2f}|{cat}'.encode()).hexdigest()[:20]
    seen[key] += 1
    expenses.append((stamp + '+08', desc, cat, f'{amount:.2f}', f'xlsx:{key}:{seen[key]}'))

# Overview tab: income, deductions and fixed costs, read from the sheet's own sections. EPF is worked out from the rate, so it is skipped.
def lines(start, stop):
    out, on = [], False
    for r in wb['Overview'].iter_rows(values_only=True):
        label = str(r[1]).strip() if r[1] is not None else ''
        if label.startswith(stop): break
        if on and label and isinstance(r[2], (int, float)):
            out.append((label.replace(' (Employee)', ''), float(r[2])))
        if label.startswith(start): on = True
    return out

plan_rows = [('income', n, a) for n, a in lines('INCOME', 'Total Gross Income')] \
          + [('deduction', n, a) for n, a in lines('EPF & STATUTORY', 'Total Deductions') if not n.startswith('EPF')] \
          + [('fixed', n, a) for n, a in lines('FIXED EXPENSES', 'Total Fixed Expenses')]
goal = wb['Savings']['C3'].value
first_day = min(e[0] for e in expenses)[:7] + '-01'

out = [
    '-- Generated by scripts/xlsx-to-sql.py. Paste into the Supabase SQL editor and run once.',
    'do $$',
    'declare',
    f'  v_email text := {q(email)};',
    '  uid uuid;',
    '  missing int;',
    '  added int;',
    'begin',
    '  select id into uid from auth.users where lower(email) = lower(v_email);',
    "  if uid is null then raise exception 'No account for %. Sign in to the app once with that email, or change the email on the line above.', v_email; end if;",
    '',
    '  create temp table _x (spent_at timestamptz, description text, category text, amount numeric, import_key text) on commit drop;',
    '  insert into _x values',
    ',\n'.join(f'    ({q(a)}, {q(b)}, {q(c)}, {d}, {q(e)})' for a, b, c, d, e in expenses) + ';',
    '',
    '  -- Categories the app does not have yet (for example Bills & Utilities) are added.',
    "  insert into public.categories (user_id, name, icon, sort)",
    "  select uid, n, '🧾', (select coalesce(max(sort), 0) from public.categories where user_id = uid) + row_number() over (order by n)",
    "  from (select distinct category n from _x) m where not exists (select 1 from public.categories c where c.user_id = uid and c.name = m.n);",
    '',
    '  select count(*) into missing from _x x where not exists (select 1 from public.categories c where c.user_id = uid and c.name = x.category);',
    "  if missing > 0 then raise exception '% rows use a category that does not exist in your app. Nothing was imported.', missing; end if;",
    '',
    "  insert into public.expenses (user_id, spent_at, description, category_id, payment_method_id, amount, source, import_key)",
    "  select uid, x.spent_at, x.description, c.id, (select id from public.payment_methods where user_id = uid and kind = 'debit' order by sort limit 1), x.amount, 'telegram', x.import_key",
    '  from _x x join public.categories c on c.user_id = uid and c.name = x.category',
    '  on conflict (user_id, import_key) do nothing;',
    '  get diagnostics added = row_count;',
    "  raise notice 'Expenses added: % (of %)', added, (select count(*) from _x);",
    '',
    '  -- The sheet has no card column, so everything imported is marked Debit card (also fixes a first run that left it blank).',
    "  update public.expenses set payment_method_id = (select id from public.payment_methods where user_id = uid and kind = 'debit' order by sort limit 1)",
    "  where user_id = uid and import_key like 'xlsx:%' and payment_method_id is null;",
    '',
    "  if not exists (select 1 from public.plan_items where user_id = uid) then",
    '    insert into public.plan_items (user_id, kind, label, amount, effective_from, sort) values',
    ',\n'.join(f"      (uid, {q(k)}, {q(n)}, {a}, date {q(first_day)}, {i})" for i, (k, n, a) in enumerate(plan_rows)) + ';',
    "    raise notice 'Income and costs added.';",
    '  else',
    "    raise notice 'You already have income and costs, so they were left alone.';",
    '  end if;',
]
if isinstance(goal, (int, float)) and goal > 0:
    out.append(f'  update public.user_settings set savings_goal = {goal} where user_id = uid and savings_goal is null;')
out += ['end $$;', '']
open('import/import.sql', 'w').write('\n'.join(out))

by_month = Counter()
for e in expenses:
    by_month[e[0][:7]] += float(e[3])
print(f'{len(expenses)} expenses, {len(plan_rows)} income/cost lines, goal {goal}')
for m, t in sorted(by_month.items()):
    print(m, f'{t:.2f}')
print(f'total {sum(by_month.values()):.2f}')
